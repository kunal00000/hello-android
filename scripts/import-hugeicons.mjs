// Import the selected MIT-licensed icons as native Android vectors.
// Usage: npm pack @hugeicons/core-free-icons@4.3.5, extract, then:
// node scripts/import-hugeicons.mjs /path/to/extracted/package
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { resolve, join } from 'node:path';
import { pathToFileURL, fileURLToPath } from 'node:url';

const source = process.argv[2];
if (!source) throw new Error('Pass the extracted @hugeicons/core-free-icons@4.3.5 package directory.');
const pkg = JSON.parse(await readFile(join(source, 'package.json'), 'utf8'));
if (pkg.name !== '@hugeicons/core-free-icons' || pkg.version !== '4.3.5') {
  throw new Error('Expected @hugeicons/core-free-icons@4.3.5. Review assets before upgrading.');
}
const icons = {
  Plus: 'Add01',
  Search: 'Search01', User: 'User', Settings: 'Settings01', Computer: 'Computer',
  More: 'MoreHorizontal', Up: 'ArrowUp02', Check: 'Tick02', Mic: 'Mic01',
  Box: 'GridView', Book: 'BookOpen01', Memory: 'Brain01', Chat: 'Message01',
  File: 'File01', Mail: 'Mail01', Phone: 'SmartPhone01', Wallet: 'Wallet01',
  Globe: 'Globe02', Moon: 'Moon02', Heart: 'Favourite', Help: 'HelpCircle',
  Edit: 'Edit02', Copy: 'Copy01', Pin: 'Pin', Camera: 'Camera01', Image: 'Image01',
  Clip: 'Attachment01', Location: 'Location01', Bot: 'Robotic', Group: 'UserGroup',
  Scan: 'Scan', Skill: 'Puzzle', Terminal: 'ComputerTerminal01', Swap: 'Exchange01',
  External: 'ArrowUpRight01', Stop: 'Stop', Trash: 'Delete02', Square: 'Square',
  Brush: 'PaintBrush01',
};
const root = fileURLToPath(new URL('../app/src/main/', import.meta.url));
const drawable = join(root, 'res/drawable');
await mkdir(drawable, { recursive: true });
const escape = value => String(value).replaceAll('&', '&amp;').replaceAll('"', '&quot;').replaceAll('<', '&lt;');
// Keep the original simple navigation/close shapes; these are maintained locally.
const entries = ['Back', 'Next', 'Close'].map(glyph =>
  `    ${glyph}(R.drawable.cue_${glyph.toLowerCase()}),`
);
for (const [glyph, name] of Object.entries(icons)) {
  const { default: nodes } = await import(pathToFileURL(resolve(source, `dist/esm/${name}Icon.js`)));
  const paths = nodes.map(([type, attributes]) => {
    if (type === 'circle') {
      const { cx, cy, r, ...rest } = attributes;
      attributes = { ...rest, d: `M${Number(cx) - Number(r)},${cy} a${r},${r} 0 1,0 ${Number(r) * 2},0 a${r},${r} 0 1,0 ${Number(r) * -2},0 Z` };
    } else if (type !== 'path') throw new Error(`Unsupported SVG element ${type} in ${name}`);
    const allowed = ['d', 'stroke', 'strokeWidth', 'strokeLinecap', 'strokeLinejoin', 'fill', 'fillRule', 'clipRule', 'key'];
    for (const key of Object.keys(attributes)) {
      if (!allowed.includes(key)) throw new Error(`Unsupported attribute ${key} in ${name}`);
    }
    const { d, stroke, strokeWidth = 1.5, strokeLinecap = 'butt', strokeLinejoin = 'miter', fill = 'none', fillRule = 'nonzero' } = attributes;
    if (![undefined, 'currentColor', 'none'].includes(stroke) || !['none', 'currentColor'].includes(fill)) {
      throw new Error(`Unexpected color in ${name}`);
    }
    return `    <path android:pathData="${escape(d)}" android:fillColor="${fill === 'none' ? '@android:color/transparent' : '#FF000000'}" android:fillType="${fillRule === 'evenodd' ? 'evenOdd' : 'nonZero'}"${stroke && stroke !== 'none' ? ` android:strokeColor="#FF000000" android:strokeWidth="${strokeWidth}" android:strokeLineCap="${strokeLinecap}" android:strokeLineJoin="${strokeLinejoin}"` : ''} />`;
  });
  const resource = `huge_${glyph.toLowerCase()}`;
  const mirrored = ['Back', 'Next', 'External'].includes(glyph) ? ' android:autoMirrored="true"' : '';
  await writeFile(join(drawable, `${resource}.xml`), `<?xml version="1.0" encoding="utf-8"?>\n<!-- Hugeicons ${name}Icon, core-free-icons 4.3.5, MIT. See assets/licenses/hugeicons.txt. -->\n<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="24dp" android:height="24dp" android:viewportWidth="24" android:viewportHeight="24"${mirrored}>\n${paths.join('\n')}\n</vector>\n`);
  entries.push(`    ${glyph}(R.drawable.${resource}),`);
}
await writeFile(join(root, 'java/dev/cue/rebuild/Icons.kt'), `package dev.cue.rebuild

import androidx.annotation.DrawableRes
import androidx.compose.material3.LocalContentColor
import androidx.compose.runtime.Composable
import androidx.compose.ui.Modifier
import androidx.compose.foundation.layout.size
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.res.painterResource
import androidx.compose.ui.unit.Dp

// Generated by scripts/import-hugeicons.mjs. Change the mapping there, then regenerate.
enum class Glyph(@DrawableRes val resource: Int) {
${entries.join('\n')}
}

@Composable
fun Icon(
    glyph: Glyph,
    modifier: Modifier = Modifier,
    tint: Color = LocalContentColor.current,
    size: Dp = Cue.IconSize,
) {
    androidx.compose.material3.Icon(
        painter = painterResource(glyph.resource),
        contentDescription = null, // The containing control owns its accessible label.
        modifier = modifier.size(size),
        tint = tint,
    )
}
`);
await mkdir(join(root, 'assets/licenses'), { recursive: true });
await writeFile(join(root, 'assets/licenses/hugeicons.txt'), await readFile(join(source, 'LICENSE.md')));
console.log(`Imported ${Object.keys(icons).length} Hugeicons vectors and generated Icons.kt.`);
